/// The six scene-and-sequel micro-beats. Scene = [goal] / [conflict] /
/// [disaster]; sequel = [reaction] / [dilemma] / [decision]. Tagged when
/// present, never required — real roleplay rarely runs the full chain, and
/// these are not the sparse book-level "Save the Cat" beats.
enum SceneBeatEnum { goal, conflict, disaster, reaction, dilemma, decision }

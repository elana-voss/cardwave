// Mirror of cardwave_names/lib/src/models/name_taxonomy.dart.
//
// The build script can't import the package directly because
// cardwave_names → cardwave_llm → Flutter SDK, and `dart run` can't
// compile Flutter sources. The output JSON only needs enum *names*
// (strings), so a local mirror serialises identically to the real
// taxonomy without dragging in Flutter.
//
// MUST stay in sync with name_taxonomy.dart. Adding/renaming any enum
// value here without updating the package (or vice versa) silently
// produces a candidate JSON the runtime can't deserialise.

